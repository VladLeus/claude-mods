import { describe, expect, test } from 'claude-code/testing'

import type { InstructionPart } from '../../types'
import { privateClaudeMdText } from '../apply/private'
import { indexMdText, partsBody, roleClaudeMdText } from '../generate/docs'
import { ARTIFACT } from './artifact'
import { EN } from './en'

/** Printable ASCII and the newline only: no byte above 0x7E and no control character but the newline. */
function isArtifactAscii(text: string): boolean {
  return /^[\x20-\x7E\n]*$/.test(text)
}

/** Whether a template keeps a brace once every well-formed `{name}` slot is taken out. */
function hasStrayBrace(template: string): boolean {
  return /[{}]/.test(template.replace(/\{[a-zA-Z]+\}/g, ''))
}

/** One part of an instruction file, as a built role file marks it. */
const PART: InstructionPart = {
  id: 'P1',
  file: 'CLAUDE.md',
  heading: 'Style',
  source: 'repo',
  text: 'Use tabs.\n',
  hash: 'a'.repeat(64),
}

describe('locales/artifact (D-221)', () => {
  test('every ARTIFACT template is printable ASCII, as the generated files were', () => {
    const bad = Object.entries(ARTIFACT).filter(([, text]) => !isArtifactAscii(text))

    expect(bad).toEqual([])
  })

  test('no EN or ARTIFACT text names an internal id, and code dir is written like its siblings (D-227)', () => {
    const texts: readonly string[] = [...Object.values(EN), ...Object.values(ARTIFACT)]

    expect(texts.filter(text => /\((P13|ISO-04|PLAN-06)\)/.test(text))).toEqual([])
    expect(texts.filter(text => text.startsWith('Code dir'))).toEqual([])
  })

  test('every ARTIFACT template has only well-formed slots', () => {
    expect(Object.entries(ARTIFACT).filter(([, text]) => hasStrayBrace(text))).toEqual([])
  })

  test("a built role file keeps today's header and part marker bytes", () => {
    expect(roleClaudeMdText('be', [])).toBe(
      "<!-- cadre: instructions for role be, built from this repo's CLAUDE.md files, rules and docs. " +
        'Edit the originals and run /cadre regen be; this file is rebuilt. -->\n',
    )
    expect(partsBody([PART])).toBe('\n\n<!-- from CLAUDE.md > Style -->\nUse tabs.\n')
  })

  test("the private role file keeps today's header bytes", () => {
    expect(privateClaudeMdText('be', 'shop', [])).toBe(
      '<!-- cadre: your global instructions for role be in shop, ' +
        'built from your global CLAUDE.md, its imports and the CLAUDE.md files above the repo. ' +
        'Private to you, never committed; rebuilt by /cadre init and /cadre regen. -->\n',
    )
  })

  test("the index keeps today's head bytes", () => {
    expect(indexMdText([], new Map())).toBe(
      [
        '# cadre roles',
        '',
        'Generated by cadre from the role definitions. Edit .cadre/<id>/role.json and run /cadre regen <id>.',
        '',
        '| Role | Purpose | Framework | Model | Scope | Launcher | Handoffs |',
        '| --- | --- | --- | --- | --- | --- | --- |',
        '',
      ].join('\n'),
    )
  })
})
